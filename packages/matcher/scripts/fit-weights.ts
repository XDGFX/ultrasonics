/**
 * Fits the matcher's Fellegi–Sunter weights and thresholds on the CC0 tier's tuning split (#132)
 * and writes them to `src/fitted-weights.ts`.
 *
 *   bun run fit-weights
 *
 * Commit its output with the held-out figures `bun test` then reports; `fellegi-sunter.test.ts`
 * fails if the constants differ from a refit, so nobody tunes them by hand.
 */
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { musicbrainzCases } from "../src/cc0-tier.ts";
import { fit } from "../src/fellegi-sunter.ts";
import { tuningCases } from "../src/split.ts";

const fitted = fit(tuningCases(musicbrainzCases));
const source = `// Generated by \`bun run fit-weights\` from the CC0 tier's tuning split. Do not edit by hand.
import type { Fitted } from "./fellegi-sunter.ts";

export const fitted: Fitted = ${JSON.stringify(fitted, null, "\t")};
`;
const target = join(import.meta.dir, "../src/fitted-weights.ts");
await writeFile(target, source);
Bun.spawnSync(["bunx", "biome", "format", "--write", target]);
console.log(await Bun.file(target).text());
